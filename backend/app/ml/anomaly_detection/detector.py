"""
SPACECARE Physiological Anomaly Detector.
NASA Space Apps Challenge 2026

Implements unsupervised physiological anomaly detection using Scikit-Learn's Isolation Forest.
Provides:
1. Inverted anomaly scoring: anomaly_score = -decision_function(X), where higher positive
   values indicate greater divergence from the trained nominal distribution.
2. Heuristic feature explanations: ranks features by standardized deviation from training
   distribution medians/spreads.

CRITICAL METHODOLOGICAL & REGULATORY LIMITATION NOTICE:
- The explanations produced by this module are HEURISTIC SUPPORTING FEATURE DEVIATIONS,
  NOT true tree path attributions or Shapley values (such as TreeSHAP).
- The anomaly scores generated by this model are UNCALIBRATED DISTANCE/ISOLATION INDICES,
  NOT medical probabilities, disease risks, or clinical diagnoses.
- This software does NOT predict or diagnose clinical diseases.
"""

from pathlib import Path
from typing import Dict, List, Optional, Tuple, Any, Union
import numpy as np
import pandas as pd
from sklearn.ensemble import IsolationForest
import joblib

from app.ml.preprocessing.feature_engineer import ML_FEATURE_COLUMNS


class PhysiologicalAnomalyDetector:
    """
    Unsupervised multi-variate anomaly detector for astronaut physiological vitals.
    Trained exclusively on nominal or early-mission baseline periods.
    """

    def __init__(
        self,
        n_estimators: int = 150,
        contamination: float = 0.05,
        max_samples: Union[str, int, float] = "auto",
        random_state: int = 42,
        decision_threshold: float = 0.0,
        feature_names: Optional[List[str]] = None
    ):
        self.n_estimators = n_estimators
        self.contamination = contamination
        self.max_samples = max_samples
        self.random_state = random_state
        self.decision_threshold = decision_threshold
        self.feature_names = feature_names or ML_FEATURE_COLUMNS

        self.model = IsolationForest(
            n_estimators=self.n_estimators,
            contamination=self.contamination,
            max_samples=self.max_samples,
            random_state=self.random_state,
            n_jobs=-1
        )
        self.is_fitted: bool = False

        # Summary statistics of the training distribution for heuristic explanation
        self.feature_centers_: Optional[np.ndarray] = None
        self.feature_scales_: Optional[np.ndarray] = None

    def fit(self, X: Union[np.ndarray, pd.DataFrame]) -> "PhysiologicalAnomalyDetector":
        """
        Fits the Isolation Forest on training feature matrices.
        Computes training distribution medians and interquartile ranges (IQR)
        for robust heuristic feature deviation attribution.
        """
        X_mat = X.to_numpy() if isinstance(X, pd.DataFrame) else np.asarray(X)

        if X_mat.ndim != 2 or X_mat.shape[1] != len(self.feature_names):
            raise ValueError(
                f"Expected input matrix with {len(self.feature_names)} features, got shape {X_mat.shape}."
            )

        self.model.fit(X_mat)
        self.is_fitted = True

        # Compute robust baseline medians and scales (IQR) for heuristic explanation
        q25 = np.percentile(X_mat, 25, axis=0)
        q75 = np.percentile(X_mat, 75, axis=0)
        iqr = q75 - q25
        # Prevent division by zero for constant features
        iqr = np.where(iqr <= 1e-6, 1.0, iqr)

        self.feature_centers_ = np.median(X_mat, axis=0)
        self.feature_scales_ = iqr

        return self

    def score_samples(self, X: Union[np.ndarray, pd.DataFrame]) -> np.ndarray:
        """
        Computes continuous anomaly score for each reading.
        Defined as: anomaly_score = -decision_function(X).
        
        Under this convention:
        - Negative scores (< 0.0): Deep inliers (highly nominal).
        - Near 0.0: Boundary region.
        - Positive scores (> 0.0): Outliers / anomalies. Larger value = higher deviation.
        """
        if not self.is_fitted:
            raise RuntimeError("PhysiologicalAnomalyDetector must be fitted before scoring.")

        X_mat = X.to_numpy() if isinstance(X, pd.DataFrame) else np.asarray(X)
        # scikit-learn decision_function is positive for inliers, negative for outliers
        return -self.model.decision_function(X_mat)

    def predict(
        self,
        X: Union[np.ndarray, pd.DataFrame],
        threshold: Optional[float] = None
    ) -> np.ndarray:
        """
        Predicts binary anomaly status based on configurable decision threshold:
        Returns boolean array: True = Anomaly, False = Nominal.
        """
        thresh = self.decision_threshold if threshold is None else threshold
        scores = self.score_samples(X)
        return scores > thresh

    def explain_reading(
        self,
        x_reading: Union[np.ndarray, pd.Series, Dict[str, float]],
        top_k: int = 3
    ) -> List[Dict[str, Any]]:
        """
        Produces heuristic supporting feature deviations explaining why a reading diverged.

        NOTICE: This is a heuristic univariate deviation ranking, NOT true Shapley tree attribution.
        Ranks features by their robust standardized deviation from the training distribution median:
            z_robust = |x_i - median_i| / IQR_i
        """
        if not self.is_fitted or self.feature_centers_ is None or self.feature_scales_ is None:
            raise RuntimeError("Detector must be fitted before explaining readings.")

        if isinstance(x_reading, dict):
            vector = np.array([float(x_reading[f]) for f in self.feature_names])
        elif isinstance(x_reading, pd.Series):
            vector = x_reading[self.feature_names].to_numpy(dtype=float)
        else:
            vector = np.asarray(x_reading, dtype=float).ravel()

        if len(vector) != len(self.feature_names):
            raise ValueError(
                f"Feature vector length {len(vector)} does not match expected {len(self.feature_names)}."
            )

        # Compute robust deviation score
        deviations = np.abs(vector - self.feature_centers_) / self.feature_scales_
        signed_diff = vector - self.feature_centers_

        # Get top-k largest deviations
        ranked_indices = np.argsort(deviations)[::-1][:top_k]

        explanations = []
        for idx in ranked_indices:
            feat_name = self.feature_names[idx]
            z_score = float(deviations[idx])
            direction = "elevated" if signed_diff[idx] > 0 else "depressed"

            # Generate objective, non-diagnostic explanation
            explanation_text = (
                f"{feat_name} is substantially {direction} relative to nominal training distribution "
                f"(robust z-score: {z_score:.2f}, observed: {vector[idx]:.2f}, median: {self.feature_centers_[idx]:.2f})"
            )

            explanations.append({
                "feature": feat_name,
                "robust_z_score": round(z_score, 2),
                "direction": direction,
                "observed_value": round(float(vector[idx]), 3),
                "training_median": round(float(self.feature_centers_[idx]), 3),
                "heuristic_explanation": explanation_text,
                "attribution_type": "HEURISTIC_SUPPORTING_FEATURE_DEVIATION"
            })

        return explanations

    def save(self, filepath: Union[str, Path]) -> None:
        """Serializes trained detector to disk using joblib."""
        path = Path(filepath)
        path.parent.mkdir(parents=True, exist_ok=True)
        joblib.dump(
            {
                "model": self.model,
                "is_fitted": self.is_fitted,
                "n_estimators": self.n_estimators,
                "contamination": self.contamination,
                "max_samples": self.max_samples,
                "random_state": self.random_state,
                "decision_threshold": self.decision_threshold,
                "feature_names": self.feature_names,
                "feature_centers_": self.feature_centers_,
                "feature_scales_": self.feature_scales_,
            },
            path
        )

    @classmethod
    def load(cls, filepath: Union[str, Path]) -> "PhysiologicalAnomalyDetector":
        """Loads serialized detector from disk."""
        data = joblib.load(filepath)
        detector = cls(
            n_estimators=data["n_estimators"],
            contamination=data["contamination"],
            max_samples=data["max_samples"],
            random_state=data["random_state"],
            decision_threshold=data["decision_threshold"],
            feature_names=data["feature_names"],
        )
        detector.model = data["model"]
        detector.is_fitted = data["is_fitted"]
        detector.feature_centers_ = data.get("feature_centers_")
        detector.feature_scales_ = data.get("feature_scales_")
        return detector
